do
    echo "Attempting to install $package via pip..."
    pip install $package
    if [ $? -ne 0 ]; then
        echo "Failed to install $package via pip, trying conda..."
        conda install -y $package
        if [ $? -ne 0 ]; then
            echo "Failed to install $package via conda, skipping."
        fi
    fi
done

